#!/usr/bin/env node
// Writes the Chalk value of every legacy shade (--ct-x-*) into the
// [data-theme='light'] block of src/theme.css, mapped from its dark value the
// way the founder-approved prototype mapped it (chalk.mjs). Rerunning it is a
// no-op; tokenize.mjs adds a shade, this gives it its light value.
//
//   node scripts/theme/light-tails.mjs           write
//   node scripts/theme/light-tails.mjs --check   exit 1 if a shade's light value is missing or stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toHex } from './colors.mjs';
import { chalk } from './chalk.mjs';
import { buildRegistry, isTail } from './roles.mjs';
import { THEME_FILE } from './sources.mjs';

export const LIGHT_START =
  '/* light-tails: generated by scripts/theme/light-tails.mjs. Rerun it instead of editing; tune a shade in its OVERRIDES. */';
export const LIGHT_END = '/* light-tails: end */';

// Shades QA tuned away from the mapping, by name.
export const OVERRIDES = {};

const format = ([r, g, b, a]) =>
  a === 1 ? `#${toHex([r, g, b])}` : `rgba(${r}, ${g}, ${b}, ${a})`;

// A `-fill` shade paints a surface; any other paints text or a line.
export const lightValue = (name, dark) =>
  OVERRIDES[name] ?? format(chalk(dark, name.endsWith('-fill') ? 'fill' : 'text'));

export const withLightTails = (themeCss) => {
  const start = themeCss.indexOf(LIGHT_START);
  const end = themeCss.indexOf(LIGHT_END, start);
  if (start === -1 || end === -1) {
    throw new Error(`${THEME_FILE} has no light-tails markers in its [data-theme='light'] block`);
  }
  const registry = buildRegistry(themeCss);
  const lines = [...registry.declared.keys()]
    .filter((name) => isTail(name) && name.startsWith('--ct-x-'))
    .sort()
    .map((name) => `  ${name}: ${lightValue(name, registry.dark(name))};`);
  return `${themeCss.slice(0, start)}${LIGHT_START}\n${lines.join('\n')}\n  ${themeCss.slice(end)}`;
};

const main = () => {
  const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const file = path.join(rootDir, THEME_FILE);
  const before = fs.readFileSync(file, 'utf8');
  const after = withLightTails(before);
  if (process.argv.includes('--check')) {
    if (after !== before) {
      console.error(`light-tails: ${THEME_FILE} is stale; run node scripts/theme/light-tails.mjs`);
      process.exitCode = 1;
    }
  } else if (after !== before) {
    fs.writeFileSync(file, after);
    console.log(`light-tails: wrote ${THEME_FILE}`);
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
