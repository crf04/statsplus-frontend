#!/usr/bin/env node
// Moves colour literals in src/ onto --ct-* tokens by the role each colour
// plays, and keeps the generated ladder and legacy-shade tokens in
// src/theme.css in step with what src/ references. Rerunning it is a no-op.
//
//   node scripts/theme/tokenize.mjs            report what would change
//   node scripts/theme/tokenize.mjs --write    apply it
//   node scripts/theme/tokenize.mjs --check    exit 1 if anything would change
//   node scripts/theme/tokenize.mjs --report out.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import valueParser from 'postcss-value-parser';
import * as prettier from 'prettier';
import { HEX_RE, parseColor } from './colors.mjs';
import {
  TAILWIND_ROLES,
  buildRegistry,
  definitionOf,
  isGenerated,
  isTail,
  misuseOf,
  onAccentContext,
  roleOf,
  tokenFor,
} from './roles.mjs';

export const THEME_FILE = 'src/theme.css';
const SKIPPED_STYLES = new Set(['src/bootstrap-subset.scss']);
export const GENERATED_START =
  '/* tokenize: generated by scripts/theme/tokenize.mjs from the tokens src/ uses. Rerun it instead of editing. */';
export const GENERATED_END = '/* tokenize: end */';

const COLOR_WORDS = new Set(['white', 'black']);
const isTestFile = (file) =>
  /\.test\.jsx?$/.test(file) || file.includes('/__tests__/') || file.endsWith('setupTests.js');

// A shadow's layers, each with its blur radius (the third length, 0 if absent).
const shadowLayers = (nodes) => {
  const layers = [[]];
  for (const node of nodes) {
    if (node.type === 'div' && node.value === ',') layers.push([]);
    else layers.at(-1).push(node);
  }
  return layers.map((layer) => {
    const lengths = layer.filter(
      (node) => node.type === 'word' && /^-?(\d*\.)?\d+([a-z]+)?$/i.test(node.value),
    );
    const blur = lengths[2] ? parseFloat(lengths[2].value) : 0;
    return { nodes: layer, blur };
  });
};

const literalOf = (node, role) => {
  if (node.type === 'word') {
    if (HEX_RE.test(node.value)) return parseColor(node.value);
    if (role && COLOR_WORDS.has(node.value.toLowerCase())) return parseColor(node.value);
    return null;
  }
  if (node.type === 'function' && /^rgba?$/i.test(node.value)) {
    const text = valueParser.stringify(node);
    return /var\(/.test(text) ? null : parseColor(text);
  }
  return null;
};

const toVar = (node, token) => {
  node.type = 'word';
  node.value = `var(${token})`;
  delete node.nodes;
};

// Rewrite the colours in one value. Returns the edits made and what it left.
const rewriteValue = (value, role, registry, context) => {
  const parsed = valueParser(value);
  const edits = [];
  const leftovers = [];

  const visit = (nodes, blur) => {
    for (const node of nodes) {
      if (node.type === 'function' && node.value === 'url') {
        if (/%23[0-9a-f]{3,8}/i.test(valueParser.stringify(node))) leftovers.push('data-uri');
        continue;
      }
      if (node.type === 'function' && /^hsla?$/i.test(node.value)) {
        leftovers.push('computed-hsl');
        continue;
      }
      if (node.type === 'function' && node.value === 'var') {
        const name = node.nodes[0]?.value ?? '';
        if (
          name.startsWith('--ct-') &&
          registry.dark(name) &&
          misuseOf(name, role, registry, context)
        ) {
          const { token } = tokenFor(registry.dark(name), role, registry, { context, blur });
          if (token && token !== name) {
            edits.push({ from: name, to: token });
            node.nodes[0].value = token;
          }
        }
        visit(node.nodes.slice(1), blur);
        continue;
      }
      const rgba = literalOf(node, role);
      if (rgba) {
        const from = valueParser.stringify(node);
        const { token, reason } = tokenFor(rgba, role, registry, { context, blur });
        if (token) {
          edits.push({ from, to: token });
          toVar(node, token);
        } else leftovers.push(reason);
        continue;
      }
      if (node.type === 'function') visit(node.nodes, blur);
    }
  };

  if (role === 'shadow') {
    for (const layer of shadowLayers(parsed.nodes)) visit(layer.nodes, layer.blur);
  } else visit(parsed.nodes, 0);

  return { value: edits.length ? valueParser.stringify(parsed) : value, edits, leftovers };
};

const hasColorLiteral = (value) => {
  let found = false;
  valueParser(value).walk((node) => {
    if (literalOf(node, 'fg')) found = true;
  });
  return found || /^\s*\d+\s*,?\s*\d+\s*,?\s*\d+\s*$/.test(value);
};

// Tokenize one stylesheet. Pure: returns the new text and what changed.
export const tokenizeCss = (css, registry) => {
  const root = postcss.parse(css);
  const rewrites = [];
  const leftovers = [];
  root.walkDecls((decl) => {
    if (decl.prop.startsWith('--ct-')) return;
    const role = roleOf(decl.prop);
    const line = decl.source?.start?.line;
    if (!role) {
      if (decl.prop.startsWith('--') && hasColorLiteral(decl.value)) {
        leftovers.push({ line, prop: decl.prop, value: decl.value, reason: 'custom-property' });
      }
      return;
    }
    const context = decl.parent?.type === 'rule' ? onAccentContext(decl.parent, registry) : null;
    const result = rewriteValue(decl.value, role, registry, context);
    for (const edit of result.edits) rewrites.push({ line, prop: decl.prop, role, ...edit });
    for (const reason of result.leftovers) {
      leftovers.push({ line, prop: decl.prop, value: decl.value, reason });
    }
    decl.value = result.value;
  });
  return { css: rewrites.length ? root.toString() : css, rewrites, leftovers };
};

const UTILITIES = Object.keys(TAILWIND_ROLES)
  .sort((a, b) => b.length - a.length)
  .join('|');
const TAILWIND_RE = new RegExp(
  `(?<![\\w-])((?:[a-z-]+:)*)(${UTILITIES})-\\[(#[0-9a-fA-F]{3,8}|rgba?\\([^\\]]*\\)|color:var\\((--ct-[a-z0-9-]+)\\))\\]`,
  'g',
);

// Tailwind arbitrary colours in JS class strings, e.g. `hover:border-[#e8a33d]`
// → `hover:border-[color:var(--ct-gold)]`. The `color:` hint keeps Tailwind
// from reading a var() as a width or a font size.
export const tokenizeTailwind = (source, registry) => {
  const rewrites = [];
  const text = source.replace(TAILWIND_RE, (match, variants, utility, value, existing, offset) => {
    const role = TAILWIND_ROLES[utility];
    const line = source.slice(0, offset).split('\n').length;
    let token;
    if (existing) {
      if (!registry.dark(existing) || !misuseOf(existing, role, registry)) return match;
      token = tokenFor(registry.dark(existing), role, registry).token;
    } else {
      const rgba = parseColor(value);
      token = rgba && tokenFor(rgba, role, registry).token;
    }
    if (!token || token === existing) return match;
    rewrites.push({ line, prop: utility, role, from: existing ?? value, to: token });
    return `${variants}${utility}-[color:var(${token})]`;
  });
  return { source: text, rewrites };
};

export const TOKEN_REFERENCE_RE = /--ct-[a-z0-9]+(?:-[a-z0-9]+)*/g;

const stripGenerated = (themeCss) => {
  const start = themeCss.indexOf(GENERATED_START);
  if (start === -1) return themeCss;
  const end = themeCss.indexOf(GENERATED_END, start);
  return themeCss.slice(0, start) + themeCss.slice(end + GENERATED_END.length);
};

// Segment by segment, alpha steps in numeric order: gold-bg-3 < gold-bg-20.
const byName = (a, b) => {
  const left = a.split('-');
  const right = b.split('-');
  for (let i = 0; i < Math.max(left.length, right.length); i += 1) {
    const [x = '', y = ''] = [left[i], right[i]];
    if (x === y) continue;
    const numeric = /^\d+(p\d+)?$/;
    if (numeric.test(x) && numeric.test(y)) {
      return Number(x.replace('p', '.')) - Number(y.replace('p', '.'));
    }
    return x < y ? -1 : 1;
  }
  return 0;
};

export const renderGenerated = (names) => {
  const sorted = [...names].sort(byName);
  const block = (selector, list) =>
    list.length
      ? `${selector} {\n${list.map((name) => `  ${name}: ${definitionOf(name)};`).join('\n')}\n}\n`
      : '';
  const tails = block(':root', sorted.filter(isTail));
  const ladder = block(
    ':root,\n[data-theme]',
    sorted.filter((name) => !isTail(name)),
  );
  return `${GENERATED_START}\n${[tails, ladder].filter(Boolean).join('\n')}${GENERATED_END}\n`;
};

// theme.css with its generated block holding exactly `names`.
export const withGenerated = (themeCss, names) => {
  const rendered = names.size ? renderGenerated(names) : '';
  const start = themeCss.indexOf(GENERATED_START);
  if (start === -1) return rendered ? `${themeCss.trimEnd()}\n\n${rendered}` : themeCss;
  const end = themeCss.indexOf(GENERATED_END, start) + GENERATED_END.length;
  const tail = themeCss.slice(end).replace(/^\n/, '');
  return themeCss.slice(0, start) + rendered + tail;
};

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });

export const sourceFiles = (rootDir) =>
  walk(path.join(rootDir, 'src'))
    .map((file) => path.relative(rootDir, file).split(path.sep).join('/'))
    .sort();

const format = async (rootDir, file, text) => {
  const filepath = path.join(rootDir, file);
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(text, { ...options, filepath });
};

// Plan every change without touching disk.
export const plan = async (rootDir) => {
  const files = sourceFiles(rootDir).filter((file) => /\.(css|scss|jsx?)$/.test(file));
  const read = (file) => fs.readFileSync(path.join(rootDir, file), 'utf8');
  const themeBefore = read(THEME_FILE);
  const registry = buildRegistry(themeBefore);
  const outputs = new Map();
  const rewrites = [];
  const leftovers = [];

  for (const file of files) {
    if (SKIPPED_STYLES.has(file)) continue;
    const before = file === THEME_FILE ? themeBefore : read(file);
    let after = before;
    if (/\.(css|scss)$/.test(file)) {
      const result = tokenizeCss(before, registry);
      after = result.css;
      rewrites.push(...result.rewrites.map((entry) => ({ file, ...entry })));
      leftovers.push(...result.leftovers.map((entry) => ({ file, ...entry })));
    } else if (/\.jsx?$/.test(file) && !isTestFile(file)) {
      const result = tokenizeTailwind(before, registry);
      after = result.source;
      rewrites.push(...result.rewrites.map((entry) => ({ file, ...entry })));
    }
    outputs.set(file, after);
  }

  // Every generated-shape name src/ references, so a hand edit that writes
  // var(--ct-hit-bg-78) gets its definition on the next run.
  const handDeclared = buildRegistry(stripGenerated(themeBefore)).declared;
  const referenced = new Set();
  for (const [file, text] of outputs) {
    const scanned = file === THEME_FILE ? stripGenerated(text) : text;
    for (const name of scanned.match(TOKEN_REFERENCE_RE) ?? []) {
      if (isGenerated(name) && !handDeclared.has(name)) referenced.add(name);
    }
  }
  outputs.set(THEME_FILE, withGenerated(outputs.get(THEME_FILE), referenced));

  const changes = [];
  for (const [file, after] of outputs) {
    const before = file === THEME_FILE ? themeBefore : read(file);
    if (after === before) continue;
    const formatted = await format(rootDir, file, after);
    if (formatted !== before) changes.push({ file, before, after: formatted });
  }
  return { changes, rewrites, leftovers, generated: [...referenced].sort(byName) };
};

const summarize = ({ changes, rewrites, leftovers, generated }) => {
  const perFile = new Map();
  for (const entry of rewrites) perFile.set(entry.file, (perFile.get(entry.file) ?? 0) + 1);
  const lines = [...perFile].map(([file, count]) => `  ${file}: ${count} rewritten`);
  return [
    `${rewrites.length} colour(s) rewritten in ${perFile.size} file(s); ${changes.length} file(s) change.`,
    ...lines,
    `${generated.length} generated token(s) in ${THEME_FILE}.`,
    `${leftovers.length} leftover(s):`,
    ...leftovers.map(
      ({ file, line, prop, value, reason }) => `  ${file}:${line} ${prop}: ${value} (${reason})`,
    ),
  ].join('\n');
};

const main = async () => {
  const args = process.argv.slice(2);
  const rootDir = path.resolve(
    args.includes('--root')
      ? args[args.indexOf('--root') + 1]
      : path.join(path.dirname(fileURLToPath(import.meta.url)), '../..'),
  );
  const result = await plan(rootDir);
  console.log(summarize(result));
  if (args.includes('--report')) {
    const { rewrites, leftovers, generated } = result;
    fs.writeFileSync(
      args[args.indexOf('--report') + 1],
      `${JSON.stringify({ rewrites, leftovers, generated }, null, 2)}\n`,
    );
  }
  if (args.includes('--write')) {
    for (const { file, after } of result.changes) fs.writeFileSync(path.join(rootDir, file), after);
    console.log(`wrote ${result.changes.length} file(s)`);
  } else if (args.includes('--check') && result.changes.length) {
    console.error(`tokenize would change: ${result.changes.map(({ file }) => file).join(', ')}`);
    process.exitCode = 1;
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
