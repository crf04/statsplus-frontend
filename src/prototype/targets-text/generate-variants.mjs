/*
 * PROTOTYPE — throwaway. Rerunnable: `node src/prototype/targets-text/generate-variants.mjs`
 * writes ./variants.css. For every rule in the Targets page's stylesheets that
 * sets an absolute font size (rem or px), it emits the same rule prefixed
 * with `body.proto-text-<V>` and the size mapped by that variant's function.
 * Sizes in em, %, clamp() or `inherit` are left alone: they follow their
 * parent. The output is also the size table a real change would apply.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..');
const SHEETS = [
  'SlatePage.css',
  'readings.css',
  'targets/TargetsPage.css',
  'targets/TargetRecord.css',
  'targets/TargetFits.css',
  'targets/TargetForm.css',
  'targets/TargetWorkbench.css',
];

const round = (px) => Math.round(px * 10) / 10;
// px in → px out.
const VARIANTS = {
  A: (px) => px * 1.15,
  // 9.6px (0.6rem) → 12.5px, 14px → 14.5px, linearly; body text +6%;
  // headings (≥ 20px) keep their size.
  B: (px) => (px < 14 ? 12.5 + ((px - 9.6) * 2) / 4.4 : px < 20 ? px * 1.06 : px),
};

const SIZE = /(\d*\.?\d+)(rem|px)\b/;
const toPx = (value, unit) => (unit === 'rem' ? value * 16 : value);

const mapDecl = (decl, fn) => {
  if (decl.prop === 'font-size') {
    const m = decl.value.trim().match(/^(\d*\.?\d+)(rem|px)$/);
    return m && decl.value.replace(SIZE, `${round(fn(toPx(+m[1], m[2])))}px`);
  }
  if (decl.prop === 'font') {
    // The first rem/px token in the shorthand is the size (weights are unitless).
    const m = decl.value.match(SIZE);
    return m && decl.value.replace(SIZE, `${round(fn(toPx(+m[1], m[2])))}px`);
  }
  return null;
};

const prefix = (selector, key) =>
  selector
    .split(',')
    .map((s) => `body.proto-text-${key} ${s.trim()}`)
    .join(',\n');

let out = `/* GENERATED by generate-variants.mjs — PROTOTYPE, throwaway. Do not edit. */\n\n`;
out += `/* Inherited text (no explicit size) grows with the containers. */
body.proto-text-A .targets-page, body.proto-text-A .target-new-modal { font-size: 18.4px; }
body.proto-text-B .targets-page, body.proto-text-B .target-new-modal { font-size: 17px; }
/* C: browser-style zoom, type and spacing together. */
body.proto-text-C .targets-page, body.proto-text-C .target-new-dialog { zoom: 1.15; }\n\n`;

let count = 0;
for (const [key, fn] of Object.entries(VARIANTS)) {
  for (const sheet of SHEETS) {
    const root = postcss.parse(readFileSync(join(src, sheet), 'utf8'), { from: sheet });
    root.walkRules((rule) => {
      if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
      const decls = [];
      rule.each((node) => {
        if (node.type !== 'decl') return;
        const value = mapDecl(node, fn);
        if (value) decls.push(`  ${node.prop}: ${value};`);
      });
      if (!decls.length) return;
      count += 1;
      let block = `${prefix(rule.selector, key)} {\n${decls.join('\n')}\n}`;
      for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) {
        block = `@${p.name} ${p.params} {\n${block}\n}`;
      }
      out += `/* ${sheet} */\n${block}\n\n`;
    });
  }
}
writeFileSync(join(here, 'variants.css'), out);
console.log(`wrote variants.css: ${count} rules`);
